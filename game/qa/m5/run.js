const { chromium } = require('playwright');
const OUT = __dirname;
const wait = (p, ms) => p.waitForTimeout(ms);
(async () => {
  const b = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const p = await b.newPage({ viewport: { width: 390, height: 800 } });
  const errs = [];
  p.on('pageerror', e => errs.push('pageerror ' + e.message + ' ' + (e.stack || '').split('\n').slice(0, 3).join(' | ')));
  p.on('console', m => { if (m.type() === 'error') errs.push('console ' + m.text()); });
  p.on('requestfailed', r => errs.push('reqfail ' + r.url()));
  await p.goto('http://localhost:8765/out/index.html');
  await p.waitForFunction(() => window.__luna && window.__luna.ready, null, { timeout: 30000 });
  await wait(p, 600);
  await p.evaluate(() => { __luna.moon('dorada'); __luna.start(); });
  await wait(p, 900);
  const st = () => p.evaluate(() => __luna.state());
  const shot = async n => { await p.screenshot({ path: OUT + `/${n}.png` }); console.log(n, JSON.stringify(await st())); };
  await p.evaluate(() => { __luna.god(true); __luna.skip(100); __luna.fast = 4; setInterval(() => __luna.unblock(), 250);
    __luna.give('ondas', 3); __luna.give('remolino', 2); __luna.give('meteoros', 4); __luna.spawn('octopus', 6, { r: 170 }); });
  await wait(p, 3500); await shot('a_art');
  await p.evaluate(() => __luna.evo('remolino')); await wait(p, 2500); await shot('a_maelstrom');
  await p.evaluate(() => __luna.skip(600)); await wait(p, 6500); await shot('h_pass');
  await wait(p, 1500); await shot('h_pass2');
  await p.evaluate(() => { const S = __luna.peek(); S.boss.ph = 'pass'; __luna.hurtBoss(1.1); }); await wait(p, 5000);
  await p.evaluate(() => __luna.skip(899)); await wait(p, 1600); await shot('z_dawn');
  console.log('ERRORS', JSON.stringify(errs.slice(0, 12)));
  await b.close();
})();
